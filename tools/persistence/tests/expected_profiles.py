"""The expected compiled profiles (formal-methods track H, slices H2.6 and H2.7, plan 4.4 and 4.7).

An expected profile is the compiled profile ``persistence compile`` emits for an example, with the contract of each generated operation
(``persistence.contract_emit``). The files are reviewed by the maintainer and compared with what ``compile`` emits by graph isomorphism
(H2.7-Q4), so an editor may lay a file out as it likes. They are also the positive fixtures of the shapes over a compiled profile
(``ontology/persistence/shapes/constraints.ttl``). The enumerations the contract names are individuals of ``ontology/persistence/spec/persistence.ttl``.

``mise run build:persistence-expected-profiles`` regenerates the files, and ``mise run check:persistence-expected-profiles`` (part of
``check:persistence``) fails with the names of the files that are not isomorphic to the output of ``compile``.
"""

from __future__ import annotations

import sys
from pathlib import Path

from rdflib import Graph
from rdflib.compare import isomorphic
from rdflib.namespace import XSD

from persistence import witness
from persistence.compiler import compile_to_graph
from persistence.contract_emit import is_declaration, mint  # noqa: F401 (the tests import them from here)
from persistence.namespaces import DAL

REPO_ROOT = Path(__file__).resolve().parents[3]
EXAMPLES = REPO_ROOT / "ontology" / "persistence" / "examples"
OUT_DIR = REPO_ROOT / "ontology" / "persistence" / "test" / "expected-profiles"

# The twelve files: eleven examples, and a variant of the first with the guards off and the caller naming each graph.
CONFIGURATIONS: list[tuple[str, str, dict]] = [
    ("baseline-single-class", "baseline-single-class", {}),
    ("epoch-dataset-level-guard", "epoch-dataset-level-guard", {}),
    ("composite-project-ownership", "composite-project-ownership", {}),
    ("append-stream-dataset-guard", "append-stream-dataset-guard", {}),
    ("uniqueness-merge-policy", "uniqueness-merge-policy", {}),
    ("uniqueness-quarantine-policy", "uniqueness-quarantine-policy", {}),
    ("claim-scheme-dual-rotation", "claim-scheme-dual-rotation", {}),
    ("value-based-cas", "value-based-cas", {}),
    ("baseline-single-class.caller-named", "baseline-single-class", {"guards": False, "graph_names": "caller"}),
    # H2.6c: the two families that append versions, a composite one and one with no boundary under the dataset-level guard.
    ("write-discipline-composite-append-versions", "write-discipline-composite-append-versions", {}),
    ("write-discipline-noboundary-append-versions", "write-discipline-noboundary-append-versions", {}),
    # H2.6f: a family that appends versions and states each version's members as changes.
    ("write-discipline-delta-membership", "write-discipline-delta-membership", {}),
]

NEW_PREDICATES = {
    DAL[n] for n in (
        "operationKind", "templateVersion", "guardStatus", "graphNaming", "declarationSource", "parameter", "access",
        "payloadContract", "digestContract", "resultColumn",
    )
}
"""The predicates a generated operation gains from its contract, which a test of the declaration rules looks for."""


def emit(example: str, *, guards: bool = True, graph_names: str = "query", source: Graph | None = None) -> Graph:
    """The compiled profile of ``examples/<example>.ttl`` under the given run choices, as ``compile`` emits it."""
    config = source if source is not None else witness._load_fixture(EXAMPLES / f"{example}.ttl")
    compiled, _ = compile_to_graph(config, guards=guards, graph_names=graph_names)
    compiled.bind("dal", DAL)
    return compiled


HEADER = """\
# SPDX-License-Identifier: CC-BY-SA-4.0
# Expected compiled profile of examples/{example}.ttl{variant}.
#
# What `persistence compile` emits for the example: the compiled profile and, for each generated operation, its kind, builder
# version, guard status, parameters, resource accesses, payload and digest contracts and result columns. Reviewed by the maintainer, and
# compared with the output of compile by graph isomorphism, so it may be laid out by any editor. The same files are the positive fixtures of
# the shapes over a compiled profile. Generated by tools/persistence/tests/expected_profiles.py. Regenerate with:
#   mise run build:persistence-expected-profiles
"""


def serialise(graph: Graph) -> str:
    graph.bind("dal", DAL)
    graph.bind("xsd", XSD)
    return graph.serialize(format="turtle")


def render_file(name: str, example: str, options: dict) -> str:
    variant = ""
    if options:
        variant = f", with the parameter guards {'on' if options.get('guards', True) else 'off'} and graphs named by the {options.get('graph_names', 'query')}"
    return HEADER.format(example=example, variant=variant) + "\n" + serialise(emit(example, **options))


def files() -> dict[str, str]:
    return {f"{name}.expected.ttl": render_file(name, example, options) for name, example, options in CONFIGURATIONS}


def stale(rendered: dict[str, str]) -> list[str]:
    """The files that are missing, that no configuration produces, or that are not isomorphic to what ``compile`` emits now."""
    out = [name for name in sorted(p.name for p in OUT_DIR.glob("*.expected.ttl")) if name not in rendered]
    for name, text in rendered.items():
        path = OUT_DIR / name
        if not path.exists() or not isomorphic(Graph().parse(path, format="turtle"), Graph().parse(data=text, format="turtle")):
            out.append(name)
    return out


def main(argv: list[str]) -> int:
    rendered = files()
    if "--write" in argv:
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        for name in stale(rendered):
            if name not in rendered:
                (OUT_DIR / name).unlink()
        for filename, text in rendered.items():
            (OUT_DIR / filename).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {len(rendered)} files to {OUT_DIR}")
        return 0
    out = stale(rendered)
    if out:
        print("stale:", ", ".join(out))
        return 1
    print("expected profiles are current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
