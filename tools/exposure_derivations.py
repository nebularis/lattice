"""Derivations over an exposure schedule (applied-insurance-reference AIR-4.3 and AIR-4.4).

Two functions, each returning triples to add and never writing into the graph it reads.
Code executes and the layer states: neither writes a triple the layer does not define.

``effective_characteristics`` (AIR-4.4, sketch §5.12) is described at its definition below.

Exposure units, derived on demand (AIR-4.3, sketch §5.11).

``exposure_units`` reads an exposure schedule and returns an ``aeo:ExposureUnit`` for every
location, asset class present at it and peril asked about, in a separate graph. It never writes
into the source graph, and nothing requires the result to be stored: a check calls it for the
perils its conditions name, evaluates over the result together with the source graph, and
discards it.

A unit's value is the sum of the amounts of the valuations of that class's assets at that
location, when they all share one value space (one currency). With several value spaces and no
conversion the sum would be meaningless, so the unit carries no value and the report says why,
since converting needs a rate and a date (Quantification's pattern). A rate valuation has no
amount and adds nothing. A peril applies to a location's unit when the location has any asset of
the class there. The function does not decide physical exposure, which a model does.

Usage::

    units, report = exposure_units(schedule, perils=[prl_voc.N_HYD_FLD], run=EX.run, exposure_set=EX.schedule)
    triples = effective_characteristics(schedule, run=EX.run)
"""

from __future__ import annotations

import hashlib
from decimal import Decimal
from typing import Dict, Iterable, List, Optional, Set, Tuple

from rdflib import BNode, Graph, Literal, Namespace, URIRef
from rdflib.namespace import RDF, XSD

AEO = Namespace("https://www.nebularis.org/neuro-semantic/insurance/exposure#")
FND = Namespace("https://www.nebularis.org/neuro-semantic/lattice/foundation#")
QNT = Namespace("https://www.nebularis.org/neuro-semantic/lattice/quantification#")
PROV = Namespace("http://www.w3.org/ns/prov#")
PRL = Namespace("https://www.nebularis.org/neuro-semantic/insurance/peril#")

DEFAULT_RUN = URIRef("urn:lattice:derivation-run:effective-characteristics")


def _members(graph: Graph, exposure_set: Optional[URIRef], prop: URIRef, cls: URIRef) -> Set[URIRef]:
    if exposure_set is not None:
        return set(graph.objects(exposure_set, prop))
    return set(graph.subjects(RDF.type, cls))


def _locations_of(graph: Graph, asset: URIRef, locations: Set[URIRef]) -> Set[URIRef]:
    """Where an asset is, as location versions of ``locations``.

    ``aeo:locatedAt`` names a location identity (AIR-66), resolved through the set's own locations.
    A presence names a location version directly."""
    identities = set(graph.objects(asset, AEO.locatedAt))
    found = {l for l in locations if graph.value(l, FND.hasIdentity) in identities}
    for presence in graph.objects(asset, AEO.presence):
        found.update(graph.objects(presence, AEO.presenceLocation))
    return {l for l in found if isinstance(l, URIRef)}


def _unit_node(run: URIRef, location: URIRef, asset_class: URIRef, peril: URIRef) -> URIRef:
    digest = hashlib.sha1(f"{location}|{asset_class}|{peril}".encode()).hexdigest()[:12]
    return URIRef(f"{run}-unit-{digest}")


def exposure_units(
    graph: Graph,
    perils: Iterable[URIRef],
    run: URIRef,
    exposure_set: Optional[URIRef] = None,
) -> Tuple[Graph, List[str]]:
    """The exposure units of ``graph``'s schedule for ``perils``, and a report of what was left out.

    ``run`` names the ``fnd:DerivationRun`` the units are generated by. With ``exposure_set``, only
    its locations, assets and valuations are read, otherwise every one in the graph is."""
    perils = list(perils)
    locations = _members(graph, exposure_set, AEO.hasLocation, AEO.Location)
    assets = _members(graph, exposure_set, AEO.hasAsset, AEO.Asset)
    valuations = _members(graph, exposure_set, AEO.hasValuation, AEO.Valuation)

    by_place: Dict[Tuple[URIRef, URIRef], Set[URIRef]] = {}
    for asset in assets:
        asset_class = graph.value(asset, AEO.assetClass)
        if asset_class is None:
            continue
        for location in _locations_of(graph, asset, locations):
            if location in locations:
                by_place.setdefault((location, asset_class), set()).add(asset)

    amounts: Dict[URIRef, List[Tuple[Decimal, URIRef]]] = {}
    for valuation in valuations:
        amount = graph.value(valuation, AEO.amount)
        target = graph.value(valuation, AEO.valueOf)  # an identity (AIR-66)
        if amount is None or target is None:
            continue
        number, space = graph.value(amount, QNT.numericValue), graph.value(amount, QNT.onSpace)
        if number is not None and space is not None:
            amounts.setdefault(target, []).append((Decimal(str(number)), space))

    units, report = Graph(), []
    units.bind("aeo", AEO)
    units.bind("fnd", FND)
    units.bind("qnt", QNT)
    units.bind("prov", PROV)
    units.add((run, RDF.type, FND.DerivationRun))

    for (location, asset_class), members in sorted(by_place.items(), key=lambda kv: (str(kv[0][0]), str(kv[0][1]))):
        figures = [f for asset in members for f in amounts.get(graph.value(asset, FND.hasIdentity), [])]
        spaces = {space for _, space in figures}
        for peril in perils:
            unit = _unit_node(run, location, asset_class, peril)
            units.add((unit, RDF.type, AEO.ExposureUnit))
            units.add((unit, AEO.unitLocation, location))
            units.add((unit, AEO.unitAssetClass, asset_class))
            units.add((unit, AEO.unitPeril, peril))
            units.add((unit, PROV.wasGeneratedBy, run))
            if len(spaces) == 1:
                value = BNode()
                units.add((unit, AEO.unitValue, value))
                units.add((value, RDF.type, QNT.Quantity))
                units.add((value, QNT.onSpace, next(iter(spaces))))
                units.add((value, QNT.numericValue, Literal(sum(n for n, _ in figures), datatype=XSD.decimal)))
            elif len(spaces) > 1:
                report.append(
                    f"{unit} has no value: the valuations at {location} for {asset_class} are in "
                    f"{len(spaces)} value spaces and the graph holds no conversion"
                )
    return units, report


_COPY = """
PREFIX aeo: <https://www.nebularis.org/neuro-semantic/insurance/exposure#>
CONSTRUCT {{ ?cause aeo:{effective} ?value }}
WHERE {{ ?cause a aeo:LossCause ; aeo:{recorded} ?value }}
"""

# A typical value is used only where nothing is recorded. The effective agency is single valued,
# so a cause concept with several typical agencies leaves it empty and a check reads Undetermined.
_DEFAULT = """
PREFIX aeo: <https://www.nebularis.org/neuro-semantic/insurance/exposure#>
PREFIX prl: <https://www.nebularis.org/neuro-semantic/insurance/peril#>
PREFIX fnd: <https://www.nebularis.org/neuro-semantic/lattice/foundation#>
PREFIX prov: <http://www.w3.org/ns/prov#>
CONSTRUCT {{
  ?cause aeo:{effective} ?value .
  ?node a aeo:DefaultedCharacteristic ;
        aeo:defaultedOn ?cause ;
        aeo:defaultedProperty aeo:{effective} ;
        prov:wasDerivedFrom ?concept ;
        prov:wasGeneratedBy <{run}> .
}}
WHERE {{
  ?cause a aeo:LossCause ; aeo:peril ?concept .
  FILTER NOT EXISTS {{ ?cause aeo:{recorded} ?recorded }}
  ?concept prl:{typical} ?value .
  {single}
  BIND(IRI(CONCAT(STR(<{run}>), "-defaulted-", MD5(CONCAT(STR(?cause), "{effective}")))) AS ?node)
}}
"""

_ONE_TYPICAL = "FILTER (1 = 1)"
_SINGLE_TYPICAL = """FILTER NOT EXISTS { ?concept prl:typicalAgency ?other . FILTER (?other != ?value) }"""


def effective_characteristics(graph: Graph, run: URIRef = DEFAULT_RUN) -> Graph:
    """The effective agency and mechanisms of every ``aeo:LossCause`` in ``graph`` (AIR-4.4).

    A recorded value is copied to ``aeo:effectiveAgency`` or ``aeo:effectiveMechanism``. Only where
    nothing is recorded is the cause concept's ``prl:typicalAgency`` or ``prl:typicalMechanism``
    used, and then one ``aeo:DefaultedCharacteristic`` per cause and property is written beside
    it, derived from the cause concept and generated by ``run``, so a reviewer sees which values
    were defaulted. The effective agency is single valued, so a cause concept with more than one
    typical agency leaves it empty, as does a cause concept with no typical values (a drafter's
    flat code). A check reading an empty effective value is Undetermined.

    The graph must hold the cause concepts' typical values (the peril vocabulary). The function
    returns the triples to add and writes no others besides the derivation run's type."""
    out = Graph()
    out.bind("aeo", AEO)
    out.bind("fnd", FND)
    out.bind("prov", PROV)
    out.add((run, RDF.type, FND.DerivationRun))
    for effective, recorded, typical, single in (
        ("effectiveAgency", "agency", "typicalAgency", _SINGLE_TYPICAL),
        ("effectiveMechanism", "mechanism", "typicalMechanism", _ONE_TYPICAL),
    ):
        for query in (
            _COPY.format(effective=effective, recorded=recorded),
            _DEFAULT.format(effective=effective, recorded=recorded, typical=typical, single=single, run=run),
        ):
            for triple in graph.query(query):
                out.add(triple)
    return out
