"""P2, a generated Isabelle theory with one `value` per case and reading over the Ledger model of the layer theories,
value output only. The theory binds each stated fact as a definition, writes a `text` where a fact is stated as not known
or not stated, so the three states never collapse, and evaluates the pro-rata split of each layer's limit over its
placements' shares and the draw of each event's loss on the primary layer. It imports the Ledger theory of the spike's
layer models, copied beside it, and builds on HOL alone. Unifying it with the mechanised layer theories is the
formal-methods tracks' work when E4a and E4b start."""

from __future__ import annotations

import logging
import os
import shutil
import subprocess
from decimal import Decimal
from pathlib import Path

from rdflib import Graph

from .cases import Case, cases, fact_state, layers_of, placements_on, rig_id
from .lift import VRIG

log = logging.getLogger("v_rig")

SESSION = "VRigP2"
THEORY = "VRigP2"


def ledger_theory() -> Path:
    import lattice_repo_catalogue as reader
    catalogue = reader.load()
    return catalogue.root / catalogue.area("spikes") / "isabelle-layers" / "Ledger.thy"


def _weights(shares: list[Decimal]) -> list[int]:
    """Decimal shares as integer weights, scaled by the largest number of decimal places among them."""
    places = max((-s.as_tuple().exponent for s in shares if s.as_tuple().exponent < 0), default=0)
    return [int(s * (Decimal(10) ** places)) for s in shares]


def _stated_int(state: dict):
    if state.get("state") == "stated" and isinstance(state.get("value"), (int, float)) and not isinstance(state.get("value"), bool):
        return int(state["value"])
    return None


def _ident(text: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in text)


def theory(graph: Graph, rig_digest: str, reading_keys: tuple[str, ...], bindings: dict[str, str], file_digests: dict[str, str]) -> str:
    lines = [
        "(* Generated by the verification rig tool from a rig's representation. Never edited by hand. *)",
        f"theory {THEORY}",
        "imports Ledger",
        "begin",
        "",
        f"text \\<open>Rig {rig_digest}. One section per case and reading. A fact stated with a value is a definition, a fact",
        "stated as not known or not stated is said in words and bound to nothing, so no value below reads a number the",
        "rig did not give.\\<close>",
        "",
    ]
    for case in cases(graph, rig_digest, reading_keys, file_digests):
        for n, reading in enumerate(case.readings or [None]):
            tag = f"c_{case.digest[:12]}_{n}"
            label = "no reading" if reading is None else f"reading {reading.key} = {reading.token}, stated by {', '.join(reading.stated_by)}"
            lines += [f"section \\<open>Case {case.digest}, programme {case.programme_id}, {label}\\<close>", ""]
            if reading is not None:
                lines += [f"definition {tag}_reading :: string where", f"  \"{tag}_reading = ''{reading.token}''\"", ""]
            for document in case.documents:
                document_id = rig_id(graph, document)
                dtag = f"{tag}_{_ident(document_id)}"
                for key in ("limit", "attachment"):
                    state = fact_state(graph, document, key)
                    value = _stated_int(state)
                    if value is not None:
                        lines += [f"definition {dtag}_{key} :: int where \"{dtag}_{key} = {value}\""]
                    elif state.get("formula"):
                        lines += [f"text \\<open>Contract {document_id}'s {key} is the formula {state['formula']}, over {', '.join(state['inputs'])}, and binds no number until they do.\\<close>"]
                    else:
                        lines += [f"text \\<open>Contract {document_id}'s {key} is {state['state']}.\\<close>"]
            lines += [""]
            layers = layers_of(graph, case)
            primary_limit = None
            for layer in layers:
                number = int(graph.value(layer, VRIG.layerNumber))
                limit, attachment = fact_state(graph, layer, "limit"), fact_state(graph, layer, "attachment")
                limit_value, attachment_value = _stated_int(limit), _stated_int(attachment)
                if limit_value is not None:
                    lines += [f"definition {tag}_layer{number}_limit :: int where \"{tag}_layer{number}_limit = {limit_value}\""]
                    if primary_limit is None:
                        primary_limit = f"{tag}_layer{number}_limit"
                elif limit.get("formula"):
                    lines += [f"text \\<open>Layer {number}'s limit is the formula {limit['formula']!s}, over {', '.join(limit['inputs'])}, and binds no number until they do.\\<close>"]
                else:
                    lines += [f"text \\<open>Layer {number}'s limit is {limit['state']}.\\<close>"]
                if attachment_value is not None:
                    lines += [f"definition {tag}_layer{number}_attachment :: int where \"{tag}_layer{number}_attachment = {attachment_value}\""]
                else:
                    lines += [f"text \\<open>Layer {number}'s attachment is {attachment['state']}.\\<close>"]
                shares = [fact_state(graph, p, "share") for p in placements_on(graph, layer)]
                decimals = [Decimal(str(s["value"])) for s in shares if s.get("state") == "stated" and isinstance(s.get("value"), (int, float))]
                if decimals and len(decimals) == len(shares) and limit_value is not None:
                    weights = _weights(decimals)
                    lines += [f"definition {tag}_layer{number}_weights :: \"int list\" where \"{tag}_layer{number}_weights = {weights}\"".replace("[", "[").replace(", ", ", "),
                              f"value \"parts {tag}_layer{number}_limit {tag}_layer{number}_weights\"",
                              f"value \"residual {tag}_layer{number}_limit {tag}_layer{number}_weights\""]
                elif shares:
                    lines += [f"text \\<open>Layer {number}'s shares are not all stated as numbers, so its split is not evaluated.\\<close>"]
                lines += [""]
            for event in case.events:
                event_id = rig_id(graph, event)
                etag = f"{tag}_{_ident(event_id)}"
                if "loss" not in bindings:
                    lines += [f"text \\<open>Event {event_id}: no input binding declares the loss, so nothing is drawn.\\<close>", ""]
                    continue
                loss = fact_state(graph, event, bindings["loss"])
                loss_value = _stated_int(loss)
                for name, key in sorted(bindings.items()):
                    if name == "loss":
                        continue
                    state = fact_state(graph, event, key)
                    rendered = f"stated as {state['value']!r}" if state.get("state") == "stated" else state["state"]
                    lines += [f"text \\<open>Event {event_id}: the input {name} is {rendered}.\\<close>"]
                if loss_value is None:
                    lines += [f"text \\<open>Event {event_id}: the loss is {loss['state']}, so nothing is drawn.\\<close>", ""]
                elif primary_limit is None:
                    lines += [f"text \\<open>Event {event_id}: the loss is {loss_value}, and no layer states a numeric limit to draw on.\\<close>", ""]
                else:
                    lines += [f"definition {etag}_loss :: int where \"{etag}_loss = {loss_value}\"",
                              f"value \"settle_at_position (\\<lambda>_. {primary_limit}) (\\<lambda>_. \\<lparr> acct = (0 :: nat), amount = {etag}_loss \\<rparr>) [0]\"",
                              ""]
    lines += ["end", ""]
    return "\n".join(lines)


def root_file() -> str:
    return "\n".join([
        "(* Generated by the verification rig tool. The session builds on HOL alone, with the Ledger theory copied beside it. *)",
        f"session {SESSION} = HOL +",
        "  options [document = false, timeout = 600]",
        "  theories",
        "    Ledger",
        f"    {THEORY}",
        "",
    ])


def write_theory(text: str, out: Path) -> list[Path]:
    directory = out / "p2"
    directory.mkdir(parents=True, exist_ok=True)
    theory_path = directory / f"{THEORY}.thy"
    theory_path.write_text(text, encoding="utf-8", newline="\n")
    (directory / "ROOT").write_text(root_file(), encoding="utf-8", newline="\n")
    shutil.copyfile(ledger_theory(), directory / "Ledger.thy")
    return [theory_path, directory / "ROOT", directory / "Ledger.thy"]


def build(out: Path) -> tuple[bool, str]:
    """Build the generated session with Isabelle, one build at a time, on HOL alone. Returns success and the output."""
    isabelle = os.environ.get("ISABELLE") or shutil.which("isabelle")
    if not isabelle:
        return False, "isabelle is not on the path and ISABELLE is not set"
    result = subprocess.run([isabelle, "build", "-d", str(out / "p2"), SESSION], capture_output=True, text=True, encoding="utf-8")
    return result.returncode == 0, result.stdout + result.stderr
