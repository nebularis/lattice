package org.nebularis.lattice.studio.store;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import org.apache.jena.atlas.json.JSON;
import org.apache.jena.atlas.json.JsonArray;
import org.apache.jena.atlas.json.JsonObject;
import org.apache.jena.atlas.json.JsonValue;
import org.apache.jena.graph.NodeFactory;
import org.apache.jena.query.ParameterizedSparqlString;
import org.apache.jena.update.Update;
import org.apache.jena.update.UpdateFactory;

/**
 * The studio's promotions kept by the write that changes their source (projection maintenance, PM2). Each promotion reads one family
 * of aggregates ({@code cst:sourceFamily}), and the writer writes such an aggregate whole, so a write of one sends, in its request,
 * the partition clear and then each of the family's fills over the whole source. A source's rows live in its own
 * graph, {@link Graphs#promoted(String)}, so a write touches only its own rows and two writes never contend for one graph (PM-Q1 (a′)).
 * The operations are generated by {@code tools/surface} and staged under {@code maintenance/}.
 */
public final class Maintenance {
    /** The families whose writes keep promotions. */
    public static final Set<String> FAMILIES = Set.of("description", "lineage", "version", "job");

    private final String clear;
    private final Map<String, List<String>> fills;

    private Maintenance(String clear, Map<String, List<String>> fills) {
        this.clear = clear;
        this.fills = fills;
    }

    /** Reads {@code folder/manifest.json}, the partition clear and every fill it names. A promotion of an unknown family fails here. */
    public static Maintenance load(Path folder) {
        try {
            JsonArray manifest = JSON.parseAny(Files.readString(folder.resolve("manifest.json"), StandardCharsets.UTF_8)).getAsArray();
            Map<String, List<String>> fills = new LinkedHashMap<>();
            for (JsonValue value : manifest) {
                JsonObject entry = value.getAsObject();
                String family = entry.getString("family");
                if (!FAMILIES.contains(family)) {
                    throw new IllegalStateException(entry.getString("key") + " reads the family " + family + ", which no write of the studio keeps");
                }
                fills.computeIfAbsent(family, k -> new ArrayList<>())
                    .add(Files.readString(folder.resolve(entry.getString("fill")), StandardCharsets.UTF_8));
            }
            return new Maintenance(Files.readString(folder.resolve("partition-clear.rq"), StandardCharsets.UTF_8), fills);
        } catch (IOException e) {
            throw new UncheckedIOException("cannot read the staged maintenance in " + folder, e);
        }
    }

    /** None, for a store whose promotions are kept some other way, as a test's. */
    public static Maintenance none() {
        return new Maintenance(null, Map.of());
    }

    /**
     * The updates that leave {@code source}'s partition holding the rows of the source as the request leaves it: the partition clear,
     * then each of the family's fills over the whole source. They are right whether or not the write before them applied, so they need
     * no guard of their own. Nothing when the family keeps no promotion.
     */
    public List<Update> keep(String family, String source) {
        List<String> those = fills.getOrDefault(family, List.of());
        if (those.isEmpty() || clear == null) {
            return List.of();
        }
        String derived = Graphs.promoted(source);
        List<Update> out = new ArrayList<>();
        out.add(bind(clear, source, derived));
        those.forEach(fill -> out.add(bind(fill, source, derived)));
        return out;
    }

    private static Update bind(String text, String source, String derived) {
        ParameterizedSparqlString bound = new ParameterizedSparqlString(text);
        if (text.contains("$source")) {
            bound.setParam("source", NodeFactory.createURI(source));
        }
        bound.setParam("derived", NodeFactory.createURI(derived));
        return UpdateFactory.create(bound.toString()).getOperations().get(0);
    }
}
