package org.nebularis.lattice.studio.store;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import org.apache.jena.atlas.json.JSON;
import org.apache.jena.atlas.json.JsonArray;
import org.apache.jena.atlas.json.JsonObject;
import org.apache.jena.atlas.json.JsonValue;
import org.apache.jena.graph.Node;
import org.apache.jena.graph.NodeFactory;
import org.apache.jena.graph.Triple;
import org.apache.jena.query.ParameterizedSparqlString;
import org.apache.jena.query.Query;
import org.apache.jena.query.QueryFactory;
import org.apache.jena.riot.out.NodeFmtLib;
import org.apache.jena.update.Update;
import org.apache.jena.update.UpdateFactory;

/**
 * The studio's promotions kept by the write that changes their source (projection maintenance, PM2). Each promotion reads one family
 * of aggregates ({@code cst:sourceFamily}), and the writer writes such an aggregate whole, so a write of one sends, in its request,
 * the partition clear and then each of the family's fills over the whole source. A source's rows live in its own
 * graph, {@link Graphs#promoted(String)}, so a write touches only its own rows and two writes never contend for one graph (PM-Q1 (a′)).
 * A promotion that reads across graphs, each hop of its read path in the graph that holds it, also has a reach query, which names the other
 * sources whose rows a write changes, so the writer keeps those in the same request ({@link #reach}).
 * The operations are generated by {@code tools/surface} and staged under {@code maintenance/}.
 */
public final class Maintenance {
    /** The families whose writes keep promotions. */
    public static final Set<String> FAMILIES = Set.of("description", "lineage", "version", "job");

    /**
     * One promotion's fill over a whole source, with the key of the contract it keeps. {@code reach} is the query that names the sources
     * another write changes the rows of, and is null for a promotion that reads its source alone, whose rows no other graph's write reaches.
     */
    public record Fill(String key, String text, String reach) {
        public Fill(String key, String text) {
            this(key, text, null);
        }
    }

    /** The slot of a reach query that holds the triples a write changed, as the rows of a {@code VALUES (?s ?p ?o)} block. */
    private static final String DELTA = "{{{delta}}}";

    /** One update of {@link #operations}, with the key of the contract whose rows it writes, and null for the partition clear. */
    public record Operation(String contract, Update update) {
    }

    private final String clear;
    private final Map<String, List<Fill>> fills;

    private Maintenance(String clear, Map<String, List<Fill>> fills) {
        this.clear = clear;
        this.fills = fills;
    }

    /**
     * A maintenance made of texts the caller holds, for a caller whose contracts are not the studio's own, such as a simulator reading the
     * operations a compile job holds. The families are the caller's, and are not checked against {@link #FAMILIES}.
     */
    public static Maintenance of(String clear, Map<String, List<Fill>> fills) {
        Map<String, List<Fill>> copy = new LinkedHashMap<>();
        fills.forEach((family, those) -> copy.put(family, List.copyOf(those)));
        return new Maintenance(clear, copy);
    }

    /** Reads {@code folder/manifest.json}, the partition clear and every fill it names. A promotion of an unknown family fails here. */
    public static Maintenance load(Path folder) {
        try {
            JsonArray manifest = JSON.parseAny(Files.readString(folder.resolve("manifest.json"), StandardCharsets.UTF_8)).getAsArray();
            Map<String, List<Fill>> fills = new LinkedHashMap<>();
            for (JsonValue value : manifest) {
                JsonObject entry = value.getAsObject();
                String family = entry.getString("family");
                if (!FAMILIES.contains(family)) {
                    throw new IllegalStateException(entry.getString("key") + " reads the family " + family + ", which no write of the studio keeps");
                }
                String reach = entry.hasKey("reach") ? Files.readString(folder.resolve(entry.getString("reach")), StandardCharsets.UTF_8) : null;
                fills.computeIfAbsent(family, k -> new ArrayList<>())
                    .add(new Fill(entry.getString("key"), Files.readString(folder.resolve(entry.getString("fill")), StandardCharsets.UTF_8), reach));
            }
            return new Maintenance(Files.readString(folder.resolve("partition-clear.rq"), StandardCharsets.UTF_8), fills);
        } catch (IOException e) {
            throw new UncheckedIOException("cannot read the staged maintenance in " + folder, e);
        }
    }

    /** None, for a store whose promotions are kept some other way, as a test's. */
    public static Maintenance none() {
        return new Maintenance(null, Map.of());
    }

    /**
     * The updates that leave {@code source}'s partition holding the rows of the source as the request leaves it: the partition clear,
     * then each of the family's fills over the whole source. They are right whether or not the write before them applied, so they need
     * no guard of their own. Nothing when the family keeps no promotion.
     */
    public List<Update> keep(String family, String source) {
        return operations(family, source).stream().map(Operation::update).toList();
    }

    /** The same updates as {@link #keep}, each with the key of the contract whose rows it writes, so a caller can tell which wrote which. */
    public List<Operation> operations(String family, String source) {
        List<Fill> those = fills.getOrDefault(family, List.of());
        if (those.isEmpty() || clear == null) {
            return List.of();
        }
        String derived = Graphs.promoted(source);
        List<Operation> out = new ArrayList<>();
        out.add(new Operation(null, bind(clear, source, derived)));
        those.forEach(fill -> out.add(new Operation(fill.key(), bind(fill.text(), source, derived))));
        return out;
    }

    /** Whether any promotion reads across graphs, so a write must say which triples it changed for {@link #reach} to name the sources it reaches. */
    public boolean reaches() {
        return fills.values().stream().anyMatch(those -> those.stream().anyMatch(f -> f.reach() != null));
    }

    /** The families that hold a promotion that reads across graphs. */
    public Set<String> reachingFamilies() {
        Set<String> out = new java.util.TreeSet<>();
        fills.forEach((family, those) -> {
            if (those.stream().anyMatch(f -> f.reach() != null)) {
                out.add(family);
            }
        });
        return out;
    }

    /**
     * The queries that name, as {@code ?src}, each source of {@code family} whose rows a write that changed {@code delta} reaches, one for
     * each promotion that reads across graphs. They read the world before the write, which is exact, since the first hop of a carrier's path
     * that a write changes has every hop before it in place on both sides of the write. The triples are given as typed terms, and a triple
     * that holds a blank node is left out, since a blank node names nothing outside its own graph. None when nothing reads across graphs or
     * no triple can be named.
     */
    public List<Query> reach(String family, java.util.Collection<Triple> delta) {
        List<String> rows = rowsOf(delta);
        if (rows.isEmpty()) {
            return List.of();
        }
        String text = String.join(" ", rows);
        List<Query> out = new ArrayList<>();
        for (Fill fill : fills.getOrDefault(family, List.of())) {
            if (fill.reach() != null) {
                out.add(QueryFactory.create(fill.reach().replace(DELTA, text)));
            }
        }
        return out;
    }

    private static boolean nameable(Triple t) {
        return !t.getSubject().isBlank() && !t.getPredicate().isBlank() && !t.getObject().isBlank();
    }

    private static List<String> rowsOf(java.util.Collection<Triple> delta) {
        return delta.stream().filter(Maintenance::nameable).map(t -> "(" + term(t.getSubject()) + " " + term(t.getPredicate()) + " " + term(t.getObject()) + ")").distinct().sorted().toList();
    }

    private static String term(Node node) {
        return NodeFmtLib.strNT(node);
    }

    private static Update bind(String text, String source, String derived) {
        ParameterizedSparqlString bound = new ParameterizedSparqlString(text);
        if (text.contains("$source")) {
            bound.setParam("source", NodeFactory.createURI(source));
        }
        bound.setParam("derived", NodeFactory.createURI(derived));
        return UpdateFactory.create(bound.toString()).getOperations().get(0);
    }
}
